#!/usr/bin/env python3
"""Generates .vscode/launch.json from .vscode/launch_gen.json.

launch_gen.json is the file you hand-edit: plain Python/C++ launch configs,
no nsys variants. For every C++ launch config in there (type "lldb-dap",
request "launch", i.e. not an "attach" config like the gdb-attach one) this
script emits a sibling "(nsys) <name>" config that runs the same binary
through scripts/nsys_profile.sh instead of the debugger.

launch.json itself is generated output — don't hand-edit it, edit
launch_gen.json and rebuild (this runs as a CMake ALL target every build).
"""
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC = REPO_ROOT / ".vscode" / "launch_gen.json"
DST = REPO_ROOT / ".vscode" / "launch.json"

HEADER = (
    "// AUTO-GENERATED by scripts/gen_launch_json.py from launch_gen.json.\n"
    "// Do not hand-edit — edit launch_gen.json instead, then rebuild.\n"
)


def nsys_variant(config: dict) -> dict:
    # lldb-dap validates that "program" is a real ELF it can launch — a shell
    # script fails with "not a valid executable". So the debuggee is /bin/bash
    # itself (a real ELF, lldb just free-runs it since stopOnEntry is false);
    # bash execs nsys_profile.sh, which execs the actual test binary.
    #
    # console: "internalConsole", not "integratedTerminal" — integratedTerminal
    # routes through lldb-dap's runInTerminal reverse-request (VS Code spawns a
    # terminal, lldb-dap rendezvous with it via a comm-file). That handshake can
    # get stuck with nothing ever exec'd and no way to kill it from the UI.
    # internalConsole has lldb-dap own the child's stdout/stderr directly and
    # stream it to the Debug Console — no handshake, real stop button works.
    name = config["name"]
    name = re.sub(r"^\(lldb-dap\)\s*", "", name)
    return {
        "name": f"(nsys) {name}",
        "type": "lldb-dap",
        "request": "launch",
        "program": "/bin/bash",
        "args": [
            "${workspaceFolder}/scripts/nsys_profile.sh",
            config["program"],
            *config.get("args", []),
        ],
        "stopOnEntry": False,
        "console": "internalConsole",
        # Without these, lldb-dap can try external/debuginfod symbol-server lookups
        # for every loaded shared library at attach time — network-dependent, and a
        # known multi-minute stall. The original (lldb-dap) configs already disable
        # this; the nsys variant was missing it.
        "initCommands": config.get("initCommands", [
            "settings set symbols.enable-external-lookup false",
            "settings set target.preload-symbols false",
        ]),
        **({"env": config["env"]} if "env" in config else {}),
    }


def is_cpp_launch(config: dict) -> bool:
    return (
        config.get("type") == "lldb-dap"
        and config.get("request") == "launch"
        and "program" in config
    )


def main() -> int:
    if not SRC.exists():
        print(f"gen_launch_json: {SRC} not found, skipping", file=sys.stderr)
        return 0

    data = json.loads(SRC.read_text())
    configs = data.get("configurations", [])

    out_configs = []
    for config in configs:
        out_configs.append(config)
        if is_cpp_launch(config):
            out_configs.append(nsys_variant(config))

    out = {"version": data.get("version", "0.2.0"), "configurations": out_configs}

    DST.write_text(HEADER + json.dumps(out, indent=4) + "\n")
    print(f"gen_launch_json: wrote {DST} ({len(out_configs)} configs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
