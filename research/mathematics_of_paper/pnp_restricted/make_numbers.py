#!/usr/bin/env python3
"""Write results/numbers.tex (LaTeX macros quoted in paper.tex) from results/summary.json and results/*.npz.

Usage: rustlib/.venv/bin/python -I research/mathematics_of_paper/pnp_restricted/make_numbers.py
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results"


def sci(x, digits=2):
    m, e = f"{x:.{digits - 1}e}".split("e")
    return rf"{m}\cdot10^{{{int(e)}}}"


def main():
    S = json.loads((RES / "summary.json").read_text())
    out = {}
    st = S["setup"]
    ista = np.load(RES / "ista.npz", allow_pickle=True)
    out["distinct"] = f"{int(st['real_data_dim'] // 8)}"
    out["realdim"] = f"{st['real_data_dim']}"
    i = S["ista"]
    out["rank"] = f"{i['rankH']}"
    out["dsup"] = f"{i['dsup']:.4f}"
    out["dlo"], out["dhi"] = f"{i['d_range'][0]}", f"{i['d_range'][1]}"
    out["dstar"] = f"{i['d_star']}"
    out["dzero"] = f"{i['d0']}"
    out["limsup"] = f"{i['limsup_bound']:.2f}"
    out["final"] = f"{i['final_err']:.2f}"
    out["limsupfactor"] = f"{i['limsup_bound'] / i['final_err']:.1f}"
    out["epszero"] = f"{i['eps0']:.3f}"
    out["ostrowski"] = f"{i['ostrowski']:.4f}"
    out["obsrate"] = f"{i['obs_rate']:.4f}"
    out["iters"] = f"{i['iters']}"
    Eb, err = ista["Eb"], ista["err"]
    ok = np.isfinite(Eb[1:len(err)])
    out["boundviol"] = f"{int(np.sum(Eb[1:len(err)][ok] < err[1:][ok] * (1 - 1e-12)))}"
    z = S["zm"]
    out["mincos"] = f"{z['min_cos_uv']:.3f}"
    out["fired"] = f"{z['fired']}"
    out["apos"] = f"{z['a_positive']}"
    out["maxlam"] = f"{z['max_lam_max']:.0f}"
    out["ratio"] = f"{z['max_restr_ratio']:.2f}"
    out["zmfinal"] = f"{z['final_err']:.2f}"
    th = np.load(RES / "theta.npz", allow_pickle=True)
    rows = []
    for t in th["theta1"]:
        e = th[f"err_{t:g}"]
        late = float(np.median(e[int(0.8 * len(e)):]))
        rows.append((t, late, float(th[f"amix_{t:g}"]), float(th[f"lmax_{t:g}"])))
    eI = th["err_I"]
    out["thetaIlate"] = f"{float(np.median(eI[int(0.8 * len(eI)):])):.2f}"
    tab = []
    for t, late, amix, lm in rows:
        ts = r"2\cdot10^{-6}" if t < 1e-5 else f"{t:g}"
        tab.append(rf"${ts}$ & {late:.2f} & {100 * amix:.0f}\,\% & {lm:.1f}\\")
    out["thetatable"] = "\n".join(tab)
    g = S["propG"]
    out["R"] = f"{g['R']}"
    out["dG"] = f"{g['d']}"

    def lin(k, f, fmt):
        return fmt.format(g[k][f]) if k in g else "--"
    names = [("I", r"$I$"), ("circ", "circulant (density)"), ("zm", "ZMSHR1 (frozen; MC dynamic)"), ("PT", r"tangent-restricted $P_T$")]
    trows = []
    for k, lab in names:
        mc = g["mc"].get(k)
        mcs = (f"{mc['mse']:.3f} & {mc['bias2']:.3f} & {mc['var']:.4f}" if mc else "-- & -- & --")
        lb = lin(k, "bias2_lin", "{:.3f}") if "bias2_lin" in g.get(k, {}) else "--"
        trows.append(f"{lab} & {lin(k, 'ratio', '{:.4f}')} & {lin(k, 'rho_T', '{:.4f}')} & {lb} & {mcs}\\\\")
    out["propGtable"] = "\n".join(trows)
    L = S["thmL"]
    rnd = [L[c] for c in L["cases"] if L[c]["kind"] == "random"]
    hr = [L[c] for c in L["cases"] if L[c]["kind"] == "haar"]
    out["kcohrand"] = f"{min(q['kcoh'] for q in rnd):.1f}--{max(q['kcoh'] for q in rnd):.1f}"
    out["kcohhaar"] = f"{min(q['kcoh'] for q in hr):.0f}--{max(q['kcoh'] for q in hr):.0f}"
    fac = []
    for q in rnd + hr:
        s_ = np.asarray(q["succ"])
        j = np.flatnonzero(s_ >= 0.9)
        if len(j):
            fac.append((q["kind"], q["Mpred"] / np.asarray(q["Ms"])[j[0]]))
    fr = [f for k, f in fac if k == "random"]
    fh = [f for k, f in fac if k == "haar"]
    out["consrand"] = f"{min(fr):.0f}--{max(fr):.0f}" if fr else "--"
    out["conshaar"] = f"{min(fh):.0f}--{max(fh):.0f}" if fh else "--"
    out["drand"] = ", ".join(str(int(q["d"])) for q in rnd)
    out["dhaar"] = ", ".join(str(int(q["d"])) for q in hr)
    lines = ["% generated by make_numbers.py -- do not edit"]
    for k, v in out.items():
        lines.append(rf"\newcommand{{\EXP{k}}}{{{v}}}")
    (RES / "numbers.tex").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
